// Runs every example program through the real emulator and prints a Markdown report
// (final registers, flags and the full execution trace). Used to produce docs/EXAMPLES.md:
//   npm run examples > ../docs/EXAMPLES.md
import { Emulator, FLAG_ORDER } from '../src/emulator/index.js';
import { EXAMPLES } from '../src/examples/programs.js';

const out = [];
out.push('# Example programs — verified output');
out.push('');
out.push('Generated by `npm run examples` (frontend/scripts/run-examples.mjs), which assembles and runs each');
out.push('example with the emulator engine. Nothing here is typed by hand.');

for (const ex of EXAMPLES) {
  const emu = new Emulator();
  const program = emu.assemble(ex.source);
  if (!program.ok) throw new Error(`${ex.id} failed to assemble`);
  emu.run();
  const s = emu.getSnapshot();
  out.push('', `## ${ex.title}`, '', ex.description, '', '```asm', ex.source.trimEnd(), '```', '');
  out.push(`**Final status:** ${s.status} after ${s.stepCount} instructions`, '');
  const regs = ['AX', 'BX', 'CX', 'DX', 'SI', 'DI', 'BP', 'SP', 'IP'];
  out.push(`| ${regs.join(' | ')} |`, `|${regs.map(() => '---').join('|')}|`, `| ${regs.map((r) => s.registersHex[r]).join(' | ')} |`, '');
  out.push(`**Flags:** ${FLAG_ORDER.map((f) => `${f}=${s.flags[f]}`).join(' ')} (FLAGS = ${s.registersHex.FLAGS}h)`, '');
  if (s.variables.length) {
    out.push(`**Variables:** ${s.variables.map((v) => `${v.name} = ${v.size === 'BYTE' ? v.value.slice(2) : v.value}h${v.count > 1 ? ' (first element)' : ''}`).join(', ')}`, '');
  }
  out.push('<details><summary>Execution trace</summary>', '');
  out.push('| # | CS:IP | Bytes | Instruction | What happened | Changes |', '|---|---|---|---|---|---|');
  for (const t of emu.getTrace()) {
    out.push(`| ${t.step} | ${t.address} | \`${t.bytes}\` | \`${t.asm}\` | ${t.description} | ${t.stages.update} |`);
  }
  out.push('', '</details>');
}
out.push('');
console.log(out.join('\n'));
